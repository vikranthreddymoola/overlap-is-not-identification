    m["DelPaySD"] = f"{d.pay_sd.mean():.2f}"
    m["DelMaxDev"] = f"{(g.theta - THETA - g.pred).abs().max():.3f}"
    unb = g[g.pred.abs() < 1e-12]
    m["DelUnbBiasMin"] = num((unb.theta - THETA).min())
    m["DelUnbBiasMax"] = num((unb.theta - THETA).max())
    m["DelUnbCovMin"] = f"{100 * unb['cov'].min():.0f}\\%"
    m["DelUnbCovMax"] = f"{100 * unb['cov'].max():.0f}\\%"
    m["DelSE"] = f"{d[d.adjustment == '+ logged forecast'].se.mean():.3f}"
    import delivery as D

