def pct0(x: float) -> str:
    v = 100 * x
    return "0\\%" if abs(v) < 0.5 else f"{v:.0f}\\%"


def diagnostic(m: Macros) -> None:
    path = os.path.join(RES, "diagnostic.csv")
    if not os.path.exists(path):
        return
    d = pd.read_csv(path)
    g = (
        d.groupby(["case", "level"], sort=False)
        .agg(
            conf=("confounded", "first"),
            absorbed=("absorbed", "median"),
            z=("z", "median"),
            zp=("z_paired", "median"),
            pre=("flag_prespec", "mean"),
            paired=("flag", "mean"),
            bias=("theta_coarse", lambda t: t.mean() - THETA),
            n=("rep", "size"),
        )
        .reset_index()
    )
    lines = [
        r"\begin{tabular}{llrrrrrrr}",
        r"\toprule",
        r" & & & & & \multicolumn{2}{c}{Pre-specified rule} & \multicolumn{2}{c}{Paired test} \\",
        r"\cmidrule(lr){6-7}\cmidrule(lr){8-9}",
        r"Refinement & Design & Level & Coarse bias & Absorbed & $z$ & Flagged & $z$ & Flagged \\",
        r"\midrule",
        r"\multicolumn{9}{l}{\emph{Coarse residual contains confounded variation}} \\",
    ]
    for conf in (True, False):
        if not conf:
            lines += [r"\addlinespace", r"\multicolumn{9}{l}{\emph{It does not}} \\"]
        for case in DIAG_LABELS:
            x = g[(g.case == case) & (g.conf == conf)]
            for r in x.itertuples():
                lab, design = DIAG_LABELS[case]
                if r.level == 0 and design in ("Rideshare", "Delivery"):
                    level = "--"
                elif design == "Study 2":
                    level = f"$\\omega = {r.level:g}$"
                elif design == "Heterogeneous":
                    level = f"$\\delta = {r.level:g}$"
                else:
                    level = f"$\\sigma_v = {r.level:g}$"
                lines.append(
                    f"{lab} & {design} & {level} & {num(r.bias)} & {pct0(r.absorbed)} & "
                    f"{num(r.z, 1)} & {100 * r.pre:.1f}\\% & {num(r.zp, 1)} & "
                    f"{100 * r.paired:.1f}\\% \\\\"
                )
    lines += [r"\bottomrule", r"\end{tabular}"]
    with open(os.path.join(PAPER, "tab_diagnostic.tex"), "w") as f:
        f.write("\n".join(lines) + "\n")
    pos, neg = g[g.conf], g[~g.conf]
    miss = pos.sort_values("pre").iloc[0]
    m["DiagPreDetectOthers"] = pct(pos[pos.index != miss.name].pre.min())
    m["DiagPreFPMax"] = pct(neg.pre.max())
    m["DiagMissFive"] = pct(miss.pre)
    m["DiagMissAbsorbed"] = f"{100 * miss.absorbed:.1f}\\%"
    m["DiagMissBias"] = num(miss.bias, 2)
    m["DiagMissZ"] = f"{abs(miss.z):.1f}"
    m["DiagMissZp"] = f"{abs(miss.zp):.0f}"
    m["DiagPairedDetectMin"] = pct(pos.paired.min())
    sel = neg[neg.case.isin(["exact_to_finer", "drop_price_only"])]
    m["DiagPairedFPPlainMax"] = pct(sel.paired.max())
    fnh = neg[neg.case == "forecast_no_hidden_info"]
    m["DiagPairedRedundMin"] = pct(fnh.paired.min())
    m["DiagPairedRedundMax"] = pct(fnh.paired.max())
    dk0 = neg[neg.case == "delivery_inputs_to_forecast_k0"].iloc[0]
    m["DiagPairedDelivery"] = pct(dk0.paired)
    dd = d[d.case == "delivery_inputs_to_forecast_k0"]
    m["DiagDeliveryGap"] = f"{abs(dd.theta_coarse.mean() - dd.theta_fine.mean()):.3f}"
    het = neg[neg.case == "het_price_only"].sort_values("level")
    m["DiagHetPairedMax"] = pct(het.paired.max())
    m["DiagHetPairedNull"] = pct(het[het.level == 0].paired.iloc[0])
    m["DiagHetPreMax"] = pct(het.pre.max())
    m["DiagHetDelta"] = f"{het.level.max():g}"
    hd = d[(d.case == "het_price_only") & (d.level == het.level.max())]
    m["DiagHetCoarse"] = f"{hd.theta_coarse.mean():.3f}"
    m["DiagHetFine"] = f"{hd.theta_fine.mean():.3f}"
    m["DiagHetFinerMax"] = pct(neg[neg.case == "het_exact_to_finer"].paired.max())
    po = neg[neg.case == "drop_price_only"].sort_values("level").iloc[0]
    m["DiagPriceOnlyAbsorbed"] = f"{100 * po.absorbed:.0f}\\%"
    m["DiagPriceOnlyZ"] = f"{abs(po.z):.1f}"
