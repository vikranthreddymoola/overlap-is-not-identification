def delivery(m: Macros) -> None:
    path = os.path.join(RES, "delivery.csv")
    if not os.path.exists(path):
        return
    d = pd.read_csv(path)
    g = (
        d.groupby(["kappa", "adjustment"], sort=False)
        .agg(
            theta=("theta", "mean"),
            pred=("predicted_bias", "mean"),
            sd=("theta", "std"),
            cov=("covers", "mean"),
            ov=("overlap", "mean"),
            exo=("exogenous_share", "mean"),
            k=("draw", "size"),
        )
        .reset_index()
    )
    lines = [
        r"\begin{tabular}{llrrrrr}",
        r"\toprule",
        r"Forecast & Adjustment set & $\hat\theta$ & Proposition~\ref{prop:bias} & Coverage & $\hat\omega$ & $\omega_V$ \\",
        r"\midrule",
    ]
    for kappa, lab in ((0.0, "Logged inputs only"), (1.0, "Also real-time supply")):
        x = g[g.kappa == kappa]
        for i, r in enumerate(x.itertuples()):
            first = lab if i == 0 else ""
            lines.append(
                f"{first} & {DELIVERY_LABELS[r.adjustment]} & {num(r.theta)} & "
                f"{num(THETA + r.pred)} & {100 * r.cov:.0f}\\% & {r.ov:.3f} & {r.exo:.3f} \\\\"
            )
        if kappa == 0.0:
            lines.append(r"\addlinespace")
    lines += [r"\bottomrule", r"\end{tabular}"]
    with open(os.path.join(PAPER, "tab_delivery.tex"), "w") as f:
        f.write("\n".join(lines) + "\n")
    key = {
        "zone + hour of week + week": "A",
        "+ logged forecast inputs": "B",
        "+ logged forecast": "C",
    }
    for r in g.itertuples():
        k = "Zero" if r.kappa == 0 else "One"
        tag = f"Del{k}{key[r.adjustment]}"
        m[f"{tag}Theta"] = num(r.theta)
        m[f"{tag}Pred"] = num(THETA + r.pred)
        m[f"{tag}Ov"] = f"{r.ov:.3f}"
        m[f"{tag}Cov"] = f"{100 * r.cov:.0f}\\%"
